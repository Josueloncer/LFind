/** Icono guardado, si sigue existiendo en la biblioteca (uno desconocido vuelve al predeterminado). */
export const folderIcon = (id: string | undefined): IconComponent | undefined => (id ? FOLDER_ICONS[id]?.Icon : undefined);

/** Búsqueda por nombre en español, sin tildes ni mayúsculas. */
const fold = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
export function searchFolderIcons(query: string, category: string | null = null): string[] {
  const q = fold(query.trim());
  const pool = category ? FOLDER_ICON_CATEGORIES.find((c) => c.id === category)?.icons ?? [] : FOLDER_ICON_CATEGORIES.flatMap((c) => c.icons);
  if (!q) return pool;
  // Escribir una categoría («música», «trabajo») muestra todos sus iconos.
  const inCategory = new Set(FOLDER_ICON_CATEGORIES.filter((c) => fold(c.label).includes(q)).flatMap((c) => c.icons));
  return pool.filter((id) => inCategory.has(id) || fold(FOLDER_ICONS[id].name).includes(q) || id.includes(q));
}
